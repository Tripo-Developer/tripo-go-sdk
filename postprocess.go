// TexturePrompt guides POST /v3/models/texture. Text, Image and Images are
// mutually exclusive, and StyleImage may only accompany Text.
type TexturePrompt struct {
	Text string `json:"text,omitempty"`

	// Image is a single reference image.
	Image *FileDescriptor `json:"image,omitempty"`

	// Images holds 2 to 4 reference images keyed by angle; the front view
	// is mandatory.
	Images []ViewImage `json:"images,omitempty"`

	// StyleImage is a style reference used together with Text.
	StyleImage *FileDescriptor `json:"style_image,omitempty"`
}

func (p *TexturePrompt) validate() error {
	kinds := 0
	if p.Text != "" {
		kinds++
	}
	if p.Image != nil {
		kinds++
	}
	if len(p.Images) > 0 {
		kinds++
	}
	if kinds > 1 {
		return errors.New("TexturePrompt.Text, Image and Images are mutually exclusive")
	}
	if p.StyleImage != nil && p.Text == "" {
		return errors.New("TexturePrompt.StyleImage requires Text")
	}
	if len(p.Images) > 0 {
		if err := validateViews(p.Images); err != nil {
			return errors.New("TexturePrompt.Images: " + err.Error())
		}
	}
	return nil
}

// TextureModelParams are the parameters for POST /v3/models/texture.
type TextureModelParams struct {
	// Input is the task_id of a Tripo-generated or imported model.
	Input string `json:"input"`

	// Model selects the texture model; see the TextureVersion constants.
	// The server defaults to TextureVersionV30.
	Model *string `json:"model,omitempty"`

	// TexturePrompt guides the new texture. It may be omitted for models
	// generated by Tripo, which then reuse their original prompt.
	TexturePrompt *TexturePrompt `json:"texture_prompt,omitempty"`

	Texture          *bool    `json:"texture,omitempty"`
	PBR              *bool    `json:"pbr,omitempty"`
	ModelSeed        *int64   `json:"model_seed,omitempty"`
	TextureSeed      *int64   `json:"texture_seed,omitempty"`
	TextureQuality   *string  `json:"texture_quality,omitempty"`
	TextureAlignment *string  `json:"texture_alignment,omitempty"`
	Compress         *string  `json:"compress,omitempty"`
	Bake             *bool    `json:"bake,omitempty"`
	PartNames        []string `json:"part_names,omitempty"`

	// Delight removes baked-in lighting from the texture. The server
	// defaults to true; it only takes effect with TextureVersionV35.
	Delight *bool `json:"delight,omitempty"`

	// Deprecated: use TexturePrompt.Text. The API ignores a top-level
	// text_prompt, so TextureModel moves this value into TexturePrompt.
	// It will be removed in 1.0.
	TextPrompt *string `json:"-"`

	// Deprecated: use TexturePrompt.Image. TextureModel moves this value
	// into TexturePrompt. It will be removed in 1.0.
	ImagePrompt *FileDescriptor `json:"-"`

	// Deprecated: use TexturePrompt.StyleImage. TextureModel moves this
	// value into TexturePrompt. It will be removed in 1.0.
	StyleImage *FileDescriptor `json:"-"`

	Extra map[string]interface{} `json:"-"`
}

// TextureModel calls POST /v3/models/texture (re-texture an existing model)
// and returns the resulting task_id.
func (c *Client) TextureModel(ctx context.Context, params TextureModelParams) (string, error) {
	if strings.TrimSpace(params.Input) == "" {
		return "", errors.New("tripo3d: TextureModel: Input (source task_id) is required")
	}
	if params.TextPrompt != nil || params.ImagePrompt != nil || params.StyleImage != nil {
		if params.TexturePrompt != nil {
			return "", errors.New("tripo3d: TextureModel: the deprecated TextPrompt, ImagePrompt and StyleImage fields cannot be combined with TexturePrompt")
		}
		prompt := &TexturePrompt{Image: params.ImagePrompt, StyleImage: params.StyleImage}
		if params.TextPrompt != nil {
			prompt.Text = *params.TextPrompt
		}
		params.TexturePrompt = prompt
	}
	if params.TexturePrompt != nil {
		if err := params.TexturePrompt.validate(); err != nil {
			return "", errors.New("tripo3d: TextureModel: " + err.Error())
		}
	}
	body, err := buildPayload(params, params.Extra)
	if err != nil {
		return "", err
	}
	return c.createTask(ctx, "/models/texture", body)
}

